const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(require('node:path').join(__dirname, '../app.js'), 'utf8');
const context = {};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('function allocateGamePayment('), source.indexOf('async function saveRoster')), context);
const unpaid = { registered: true, selected: true, attended: true, paid: false, amount: null };
const records = { '2026-10-01': { p: { ...unpaid } }, '2026-10-08': { p: { ...unpaid } } };
let rows = context.allocateGamePayment(records, '2026-10-25', 'p', { ...unpaid, amount: 20 }, 10);
assert.equal(rows[0].game_date, '2026-10-01');
assert.equal(rows[0].paid, true);
assert.equal(rows[0].amount, '10.00');
assert.equal(rows.at(-1).amount, '10.00');
assert.equal(rows.reduce((n, row) => n + Number(row.amount), 0), 20);
rows = context.allocateGamePayment({}, '2026-10-25', 'p', { ...unpaid, amount: 20 }, 10);
assert.equal(rows[0].amount, '20.00');
rows = context.allocateGamePayment(records, '2026-10-25', 'p', { ...unpaid, amount: 35 }, 10);
assert.equal(rows.length, 3);
assert.equal(rows.at(-1).amount, '15.00');
assert.equal(rows.reduce((n, row) => n + Number(row.amount), 0), 35);
rows = context.allocateGamePayment({ '2026-10-01': { p: { ...unpaid, amount: 4 } } }, '2026-10-25', 'p', { ...unpaid, amount: 13 }, 10);
assert.equal(rows[0].amount, '7.00');
assert.equal(rows[0].paid, false);
assert.equal(rows.at(-1).amount, '10.00');
console.log('Payment allocation checks passed');
