const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(require('node:path').join(__dirname, '../app.js'), 'utf8');
const context = {};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('function allocateGamePayment('), source.indexOf('async function saveRoster')), context);
const unpaid = { registered: true, selected: true, attended: true, paid: false, amount: null };
const records = { '2026-10-01': { p: { ...unpaid } }, '2026-10-08': { p: { ...unpaid } } };
let rows = context.allocateGamePayment(records, '2026-10-25', 'p', { ...unpaid, amount: 20 }, 10);
assert.equal(rows[0].game_date, '2026-10-01');
assert.equal(rows[0].paid, true);
assert.equal(rows[0].amount, '10.00');
assert.equal(rows.at(-1).amount, '10.00');
assert.equal(rows.reduce((n, row) => n + Number(row.amount), 0), 20);
rows = context.allocateGamePayment({}, '2026-10-25', 'p', { ...unpaid, amount: 20 }, 10);
assert.equal(rows[0].amount, '20.00');
rows = context.allocateGamePayment(records, '2026-10-25', 'p', { ...unpaid, amount: 35 }, 10);
assert.equal(rows.length, 3);
assert.equal(rows.at(-1).amount, '15.00');
assert.equal(rows.reduce((n, row) => n + Number(row.amount), 0), 35);
rows = context.allocateGamePayment({ '2026-10-01': { p: { ...unpaid, amount: 4 } } }, '2026-10-25', 'p', { ...unpaid, amount: 13 }, 10);
assert.equal(rows[0].amount, '7.00');
assert.equal(rows[0].paid, false);
assert.equal(rows.at(-1).amount, '10.00');
console.log('Payment allocation checks passed');
const exempt = { ...unpaid, is_twelfth_man: true };
rows = context.allocateGamePayment({ '2026-10-01': { p: exempt } }, '2026-10-25', 'p', { ...unpaid, amount: 20 }, 10);
assert.equal(rows.length, 1, 'Never allocate money to an exempt reserve game');
rows = context.allocateGamePayment(records, '2026-10-25', 'p', { ...exempt, amount: 20 }, 10);
assert.equal(rows.length, 3);
assert.equal(rows.at(-1).amount, '0.00');
assert.equal(rows.reduce((n, row) => n + Number(row.amount), 0), 20);
vm.runInContext(source.slice(source.indexOf('function twelfthManId('), source.indexOf('const defaultLogoUrl')), context);
assert.equal(context.twelfthManId({ marcus: { selected: true, is_twelfth_man: true }, tony: { selected: true } }), 'marcus');
assert.equal(context.twelfthManId({ tony: { selected: true } }), null, 'Do not guess without a server designation');
console.log('Server designation and reserve fee checks passed');
context.state = { club: { game_fee: 10 }, games: [{ date: '2026-10-17' }], register: { '2026-10-17': { p: exempt } } };
context.todayKey = () => '2026-10-23';
context.selectedDate = '2026-10-25';
vm.runInContext(source.slice(source.indexOf('function playerFinancialBalance('), source.indexOf('function renderRoster(')), context);
assert.equal(context.playerFinancialBalance('p'), 0, 'Attending 12th Man owes nothing');
assert.equal(context.previousFeesOwing('p'), 0);
context.state.register['2026-10-17'].p.amount = 10;
assert.equal(context.playerFinancialBalance('p'), 10, 'Preserve recorded payment as credit');
context.state.register['2026-10-17'].p = unpaid;
assert.equal(context.playerFinancialBalance('p'), -10, 'Ordinary attendee still owes the fee');
assert.equal(context.previousFeesOwing('p'), 10);
console.log('Reserve balance and arrears checks passed');
